    def predict_season_with_dual_output(self, df_full: pd.DataFrame, target_year: int) -> pd.DataFrame:
        """
        NEW v6.0: Predict points per game and convert to total points rankings.
        
        Creates dual output:
        (a) Total points based on actual games played in target year
        (b) Total points projected to 82 games
        
        Args:
            df_full: Complete dataset including target year
            target_year: Year to predict (e.g., 2024 for 2024-2025 season)
            
        Returns:
            DataFrame with predictions and dual total points calculations
        """
        if self.model is None:
            raise ValueError("Model must be trained first")
            
        # Get target year data
        target_data = df_full[df_full['year'] == target_year].copy()
        
        if len(target_data) == 0:
            raise ValueError(f"No data found for year {target_year}")
        
        print(f"\nPredicting {target_year} season with dual output:")
        print(f"  Players to predict: {len(target_data)}")
        
        # Prepare features
        X_pred, _ = self.prepare_features(target_data)
        
        # Apply feature selection if used during training
        if self.feature_selector is not None:
            X_pred_selected = X_pred[self.selected_features]
        else:
            X_pred_selected = X_pred
        
        print(f"  Players with complete feature data: {len(X_pred_selected)}")
        
        # Scale features if linear model
        if hasattr(self.scaler, 'transform') and self.best_params and self.model.__class__.__name__ in ['Ridge', 'Lasso', 'ElasticNet']:
            X_pred_final = self.scaler.transform(X_pred_selected)
        else:
            X_pred_final = X_pred_selected
        
        # Make predictions (points per game)
        predicted_ppg = self.model.predict(X_pred_final)
        
        # Create results dataframe
        results_df = target_data.loc[X_pred_selected.index].copy()
        results_df['predicted_ppg'] = predicted_ppg
        
        # NEW v6.0: Convert to total points for ranking
        # (a) Actual games played
        results_df['actual_games'] = results_df['games_played'].fillna(0)
        results_df['predicted_points_actual'] = results_df['predicted_ppg'] * results_df['actual_games']
        
        # (b) Projected to 82 games
        results_df['predicted_points_82games'] = results_df['predicted_ppg'] * 82
        
        # Add actual total points for comparison
        if 'total_points' in results_df.columns:
            results_df['actual_total_points'] = results_df['total_points']
        elif 'points_player' in results_df.columns:
            results_df['actual_total_points'] = results_df['points_player']
        else:
            results_df['actual_total_points'] = results_df.get('goals', 0) + results_df.get('assists', 0)
        
        # Sort by predicted total points (82 games) for ranking
        results_df = results_df.sort_values('predicted_points_82games', ascending=False)
        
        # Return relevant columns
        return_cols = ['player_name', 'predicted_ppg', 'actual_games', 
                      'predicted_points_actual', 'predicted_points_82games', 'actual_total_points']
        
        return results_df[return_cols].reset_index(drop=True)
    
    def get_enhanced_feature_importance(self, top_n: int = 25) -> pd.DataFrame:
        """
        Enhanced feature importance analysis for v6.0.
        
        Args:
            top_n: Number of top features to return
            
        Returns:
            DataFrame with enhanced feature categorization
        """
        if self.model is None:
            raise ValueError("Model must be trained first")
        
        # Get importance values
        if hasattr(self.model, 'feature_importances_'):
            importance = self.model.feature_importances_
        else:
            importance = np.abs(self.model.coef_)
        
        feature_names = self.selected_features if self.selected_features else self.feature_columns
        
        importance_df = pd.DataFrame({
            'feature': feature_names,
            'importance': importance
        }).sort_values('importance', ascending=False)
        
        # Enhanced categorization for v6.0
        def categorize_feature_v6(feature_name):
            if 'covid' in feature_name.lower():
                return "COVID"
            elif 'years_played' in feature_name or 'rookie' in feature_name or 'prime' in feature_name or 'veteran' in feature_name:
                return "EXPERIENCE"
            elif '_x_' in feature_name:
                return "INTERACTION"
            elif any(team_indicator in feature_name.lower() for team_indicator in ['wins', 'losses', 'goals_for', 'goals_against']):
                return "TEAM"
            elif feature_name.startswith('pp'):
                return "POWERPLAY"
            else:
                return "INDIVIDUAL"
        
        importance_df['type'] = importance_df['feature'].apply(categorize_feature_v6)
        
        return importance_df.head(top_n)
    
