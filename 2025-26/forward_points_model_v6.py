        if self.use_feature_selection and len(self.feature_columns) > 20:
            print(f"  Applying enhanced feature selection...")
            # More conservative feature selection for polynomial/interaction terms
            k_features = min(50, max(15, len(self.feature_columns) // 3))  # More features allowed
            self.feature_selector = SelectKBest(score_func=f_regression, k=k_features)
