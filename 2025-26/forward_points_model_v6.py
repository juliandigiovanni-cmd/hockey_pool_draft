    def create_lag_features(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Create lagged features including updated team structure and experience interactions.
        
        NEW v6.0 Updates:
        - Updated team feature identification for new structure (wins to face_off_win_pct_team)
        - Includes experience features in lag creation
        - Creates interaction terms between lagged stats and experience
        
        Args:
            df: DataFrame with enhanced features including experience
            
        Returns:
            DataFrame with comprehensive lag features
        """
        # Individual stats for lagging
        individual_features = ['goals', 'assists', 'shots', 'games_played', 'shooting_pct', 
                             'time_on_ice_per_game', 'points_per_game', 'total_points']
        
        # Power play features
        pp_features = [col for col in df.columns if col.startswith('pp') and 'lag' not in col]
        
        # NEW v6.0: Updated team feature identification
        # Look for team features from "wins" to "face_off_win_pct_team"
        team_features = self._identify_team_features(df)
        
        # Experience features to lag
        experience_features = ['years_played', 'years_played_squared', 'years_played_cubed']
        
        # Combine all features for lagging
        all_lag_features = individual_features + pp_features + team_features + experience_features
        existing_features = [f for f in all_lag_features if f in df.columns]
        
        print(f"\nCreating {self.lag_years}-year lags for {len(existing_features)} features:")
        print(f"  Individual stats: {len([f for f in existing_features if f in individual_features])}")
        print(f"  Power play stats: {len([f for f in existing_features if f in pp_features])}")
        print(f"  Team statistics: {len([f for f in existing_features if f in team_features])}")
        print(f"  Experience features: {len([f for f in existing_features if f in experience_features])}")
        
        df_with_lags = df.copy()
        
        # Initialize lag columns
        lag_columns = []
        for feature in existing_features:
            for lag in range(1, self.lag_years + 1):
                lag_col = f'{feature}_lag{lag}'
                lag_columns.append(lag_col)
                df_with_lags[lag_col] = np.nan
        
        print(f"  Total lag columns created: {len(lag_columns)}")
        
        # Create lags for each player individually
        players_with_sufficient_history = 0
        
        for player in df['player_id'].unique():
            player_data = df[df['player_id'] == player].sort_values('year')
            
            if len(player_data) > self.lag_years:
                players_with_sufficient_history += 1
                
                for feature in existing_features:
                    for lag in range(1, self.lag_years + 1):
                        lag_col = f'{feature}_lag{lag}'
                        lagged_values = player_data[feature].shift(lag)
                        df_with_lags.loc[df_with_lags['player_id'] == player, lag_col] = lagged_values
        
        print(f"Players with sufficient history: {players_with_sufficient_history}")
        
        # Filter to training years
        training_data = df_with_lags[df_with_lags['year'] >= self.min_training_year].copy()
        print(f"Training data shape after year filter: {training_data.shape}")
        
        return training_data
    
    def _identify_team_features(self, df: pd.DataFrame) -> List[str]:
        """
        NEW v6.0: Identify team features based on new structure.
        
        Team features now run from "wins" to "face_off_win_pct_team" instead of 
        the old team1, team2, team3 numbering system.
        
        Args:
            df: DataFrame with team statistics
            
        Returns:
            List of team feature column names
        """
        team_features = []
        
        # Check if we have the expected team structure
        if 'wins' in df.columns and 'face_off_win_pct_team' in df.columns:
            # Get all columns between wins and face_off_win_pct_team
            cols = list(df.columns)
            try:
                start_idx = cols.index('wins')
                end_idx = cols.index('face_off_win_pct_team')
                team_features = cols[start_idx:end_idx+1]
                print(f"  Identified {len(team_features)} team features from 'wins' to 'face_off_win_pct_team'")
            except ValueError:
                print("  Warning: Could not find team feature range")
        
        # Fallback: look for any remaining team-like features
        if not team_features:
            # Look for columns that might be team stats
            possible_team_cols = [col for col in df.columns if any(indicator in col.lower() 
                                 for indicator in ['team', 'wins', 'losses', 'goals_for', 'goals_against'])]
            team_features.extend(possible_team_cols)
            
        # Remove any non-numeric columns
        numeric_team_features = []
        for col in team_features:
            if col in df.columns:
                try:
                    pd.to_numeric(df[col], errors='raise')
                    numeric_team_features.append(col)
                except:
                    continue
        
        print(f"  Final team features for lagging: {numeric_team_features[:10]}...")  # Show first 10
        return numeric_team_features
    
    def engineer_features(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Enhanced feature engineering with experience interactions and non-linear terms.
        
        NEW v6.0 Features:
        - Interaction terms between experience and performance
        - Non-linear transformations of key variables
        - COVID season interaction effects
        - Enhanced career trajectory features
        
        Args:
            df: DataFrame with lag features
            
        Returns:
            DataFrame with comprehensive engineered features
        """
        print(f"\nEngineering enhanced features with experience and non-linear terms...")
        
        df_eng = df.copy()
        
        # Find all lag columns
        lag_columns = [col for col in df_eng.columns if 'lag' in col]
        
        if lag_columns:
            print(f"Found {len(lag_columns)} lag columns for feature engineering")
            
            # Get base features that have lags
            base_features = list(set([col.replace('_lag1', '').replace('_lag2', '').replace('_lag3', '') 
                                    for col in lag_columns]))
            
            print(f"Engineering features for {len(base_features)} base features")
            
            # Standard lag-based features (from v5.3)
            for base_feature in base_features:
                lag_cols = [col for col in lag_columns if col.startswith(f'{base_feature}_lag')]
                
                if lag_cols:
                    # Historical averages
                    df_eng[f'{base_feature}_hist_avg'] = df_eng[lag_cols].mean(axis=1, skipna=True)
                    
                    # Historical consistency (if multiple lags)
                    if len(lag_cols) >= 2:
                        df_eng[f'{base_feature}_hist_std'] = df_eng[lag_cols].std(axis=1, skipna=True).fillna(0)
                    
                    # Recent trends
                    if len(lag_cols) >= 2 and f'{base_feature}_lag1' in df_eng.columns and f'{base_feature}_lag2' in df_eng.columns:
                        trend = df_eng[f'{base_feature}_lag1'] - df_eng[f'{base_feature}_lag2']
                        df_eng[f'{base_feature}_trend'] = trend.fillna(0)
            
            # NEW v6.0: Experience interaction terms
            self._create_experience_interactions(df_eng, lag_columns)
            
            # NEW v6.0: COVID season interactions
            self._create_covid_interactions(df_eng, lag_columns)
            
            # NEW v6.0: Career trajectory features
            self._create_career_trajectory_features(df_eng)
        
        # Create per-game rates from historical data (focus on individual stats)
        for lag in range(1, min(self.lag_years + 1, 3)):
            if f'goals_lag{lag}' in df_eng.columns and f'games_played_lag{lag}' in df_eng.columns:
                goals_per_game = df_eng[f'goals_lag{lag}'] / df_eng[f'games_played_lag{lag}'].replace(0, np.nan)
                df_eng[f'goals_per_game_lag{lag}'] = goals_per_game.fillna(0)
                
            if f'assists_lag{lag}' in df_eng.columns and f'games_played_lag{lag}' in df_eng.columns:
                assists_per_game = df_eng[f'assists_lag{lag}'] / df_eng[f'games_played_lag{lag}'].replace(0, np.nan)
                df_eng[f'assists_per_game_lag{lag}'] = assists_per_game.fillna(0)
        
        # Clean up infinite and extreme values
        df_eng = df_eng.replace([np.inf, -np.inf], np.nan)
        
        # Fill remaining NaN values with appropriate defaults
        numeric_cols = df_eng.select_dtypes(include=[np.number]).columns
        df_eng[numeric_cols] = df_eng[numeric_cols].fillna(0)
        
        print(f"Final engineered data shape: {df_eng.shape}")
        
        return df_eng
    
    def _create_experience_interactions(self, df_eng: pd.DataFrame, lag_columns: List[str]) -> None:
        """
        NEW v6.0: Create interaction terms between experience and performance.
        
        These interactions allow performance metrics to have different effects
        based on player experience level (rookies vs veterans).
        
        Args:
            df_eng: DataFrame to add interaction terms to
            lag_columns: List of lag column names
        """
        print("  Creating experience interaction terms...")
        
        # Key performance metrics to interact with experience
        key_performance_lags = [col for col in lag_columns 
                               if any(metric in col for metric in ['goals_lag', 'assists_lag', 'points_per_game_lag', 'shots_lag'])]
        
        # Create interactions with years_played
        interaction_count = 0
        for perf_col in key_performance_lags[:15]:  # Limit to prevent feature explosion
            if perf_col in df_eng.columns and 'years_played' in df_eng.columns:
                interaction_name = f'{perf_col}_x_experience'
                df_eng[interaction_name] = df_eng[perf_col] * df_eng['years_played']
                interaction_count += 1
        
        print(f"    Created {interaction_count} experience interaction terms")
    
