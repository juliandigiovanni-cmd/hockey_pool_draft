    def _create_points_per_game_target(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        NEW v6.0: Create points per game target variable.
        
        This is a more stable target than total points as it accounts for:
        - Injury-shortened seasons
        - COVID-affected seasons with different game counts
        - Trade scenarios where players play partial seasons
        
        Args:
            df: DataFrame with player statistics
            
        Returns:
            DataFrame with points_per_game target variable
        """
        print("\nCreating points per game target variable...")
        
        # Use points_player if available, otherwise calculate from goals + assists
        if 'points_player' in df.columns:
            df['total_points'] = df['points_player'].fillna(0)
            print("Using 'points_player' column for points calculation")
        elif 'goals' in df.columns and 'assists' in df.columns:
            df['total_points'] = df['goals'].fillna(0) + df['assists'].fillna(0)
            print("Calculating points from goals + assists")
        else:
            raise ValueError("Cannot find points_player column or goals+assists columns")
        
        # Handle games played column variations
        games_played_cols = ['games_played_player', 'games_played', 'gamesPlayed', 'GP', 'Games', 'games', 'Games_Played', 'gp']
        games_played_col = None
        
        for col in games_played_cols:
            if col in df.columns:
                games_played_col = col
                break
        
        if games_played_col:
            df['games_played'] = df[games_played_col].fillna(0).clip(lower=0)
            if games_played_col != 'games_played':
                print(f"Using '{games_played_col}' column for games played")
        else:
            raise ValueError(f"Cannot find games played column. Available columns: {list(df.columns)}")
        
        # Calculate points per game, handling division by zero
        
        # Only calculate points per game for players with games played > 0
        valid_games_mask = df['games_played'] > 0
        df.loc[valid_games_mask, 'points_per_game'] = (
            df.loc[valid_games_mask, 'total_points'] / df.loc[valid_games_mask, 'games_played']
        )
        
        # For players with 0 games, set points per game to 0
        df.loc[~valid_games_mask, 'points_per_game'] = 0
        
        # Basic statistics for points per game
        ppg_stats = df[df['points_per_game'] > 0]['points_per_game'].describe()
        print(f"Points per game statistics:")
        print(f"  Mean: {ppg_stats['mean']:.3f}")
        print(f"  Median: {ppg_stats['50%']:.3f}")
        print(f"  Max: {ppg_stats['max']:.3f}")
        print(f"  Players with >0 PPG: {len(df[df['points_per_game'] > 0])}")
        
        return df
    
    def _create_covid_season_indicators(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        NEW v6.0: Create indicator variables for COVID-affected seasons.
        
        The 2019-2020 and 2020-2021 seasons were significantly affected by COVID:
        - 2019-2020: Season suspended in March, shortened season
        - 2020-2021: Shortened season, different divisions, no fans
        
        Args:
            df: DataFrame with year information
            
        Returns:
            DataFrame with COVID season indicators
        """
        print("\nCreating COVID season indicators...")
        
        # Create COVID season indicators
        df['covid_2019_2020'] = (df['year'] == 2019).astype(int)
        df['covid_2020_2021'] = (df['year'] == 2020).astype(int)
        df['covid_season'] = ((df['year'] == 2019) | (df['year'] == 2020)).astype(int)
        
        covid_2019_count = df['covid_2019_2020'].sum()
        covid_2020_count = df['covid_2020_2021'].sum()
        total_covid = df['covid_season'].sum()
        
        print(f"COVID season indicators created:")
        print(f"  2019-2020 season observations: {covid_2019_count}")
        print(f"  2020-2021 season observations: {covid_2020_count}")
        print(f"  Total COVID-affected observations: {total_covid}")
        
        return df
    
    def _calculate_years_played(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        NEW v6.0: Calculate years played (career experience) for each player.
        
        Years played = Current season year - First season year + 1
        This creates an experience feature that can capture:
        - Rookie effects (years_played = 1)
        - Prime years (years_played = 3-10)
        - Veteran effects (years_played > 10)
        - Aging curves and career trajectories
        
        Args:
            df: DataFrame with player seasons
            
        Returns:
            DataFrame with years_played and related experience features
        """
        print("\nCalculating years played (experience features)...")
        
        # Calculate first season for each player
        first_seasons = df.groupby('player_id')['year'].min().reset_index()
        first_seasons.rename(columns={'year': 'first_season_year'}, inplace=True)
        
        # Merge back to main dataframe
        df = df.merge(first_seasons, on='player_id', how='left')
        
        # Calculate years played (career length at each observation)
        df['years_played'] = df['year'] - df['first_season_year'] + 1
        
        # Ensure years played is at least 1 and reasonable
        df['years_played'] = df['years_played'].clip(lower=1, upper=25)
        
        # NEW v6.0: Create polynomial terms for non-linear career effects
        df['years_played_squared'] = df['years_played'] ** 2
        df['years_played_cubed'] = df['years_played'] ** 3
        
        # Career stage indicators
        df['rookie_year'] = (df['years_played'] == 1).astype(int)
        df['prime_years'] = ((df['years_played'] >= 3) & (df['years_played'] <= 10)).astype(int)
        df['veteran_years'] = (df['years_played'] > 10).astype(int)
        
        # Experience statistics
        exp_stats = df['years_played'].describe()
        print(f"Years played statistics:")
        print(f"  Mean: {exp_stats['mean']:.1f} years")
        print(f"  Median: {exp_stats['50%']:.1f} years")
        print(f"  Max: {exp_stats['max']:.0f} years")
        print(f"  Rookies (1 year): {df['rookie_year'].sum()} observations")
        print(f"  Prime years (3-10): {df['prime_years'].sum()} observations")
        print(f"  Veterans (>10 years): {df['veteran_years'].sum()} observations")
        
        return df
    
    def _clean_missing_data(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Clean and handle missing data with enhanced domain knowledge for v6.0.
        
        Args:
            df: Raw DataFrame with potential missing data issues
            
        Returns:
            Cleaned DataFrame with missing data handled appropriately
        """
        print("\nCleaning missing data...")
        
        # Handle shooting percentage variations
        shooting_cols = ['shooting_pct', 'shooting_percentage', 'sh_pct', 'shootingPct']
        shooting_col = None
        for col in shooting_cols:
            if col in df.columns:
                shooting_col = col
                break
        
        if shooting_col:
            # Convert percentage to decimal if needed
            if df[shooting_col].max() > 1:
                df['shooting_pct'] = df[shooting_col] / 100
            else:
                df['shooting_pct'] = df[shooting_col]
        else:
            # Calculate shooting percentage from goals and shots if available
            goals_cols = ['goals', 'Goals', 'G']
            shots_cols = ['shots', 'Shots', 'S']
            
            goals_col = None
            shots_col = None
            
            for col in goals_cols:
                if col in df.columns:
                    goals_col = col
                    break
            for col in shots_cols:
                if col in df.columns:
                    shots_col = col
                    break
            
            if goals_col and shots_col:
                df['shooting_pct'] = df[goals_col] / df[shots_col].replace(0, np.nan)
                df['shooting_pct'] = df['shooting_pct'].fillna(0.1)  # League average fallback
                # Ensure we have standardized column names
                if goals_col != 'goals':
                    df['goals'] = df[goals_col]
                if shots_col != 'shots':
                    df['shots'] = df[shots_col]
            else:
                df['shooting_pct'] = 0.1  # League average fallback
        
        # Handle time_on_ice_per_game variations
