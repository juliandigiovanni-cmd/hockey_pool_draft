    def predict_season_with_combined_ranking(self, df_full: pd.DataFrame, target_year: int) -> pd.DataFrame:
        """
        NEW v1.4: Predict both points and plus/minus using separate models with different feature sets.
        
        Args:
            df_full: Complete dataset including target year
            target_year: Year to predict (e.g., 2024 for 2024-2025 season)
            
        Returns:
            DataFrame with comprehensive predictions and rankings for all categories
        """
        if self.model_points is None or self.model_plusminus is None:
            raise ValueError("Both models must be trained first")
        
        # Get target year data
        target_data = df_full[df_full['year'] == target_year].copy()
        
        if len(target_data) == 0:
            raise ValueError(f"No defensemen data found for year {target_year}")
        
        print(f"\nNEW v1.4: Predicting {target_year} season for defensemen with ENHANCED ranking:")
        print(f"  Defensemen to predict: {len(target_data)}")
        print(f"  ENHANCED models trained with improved plus/minus modeling")
        
        # Prepare separate feature sets
        X_pred, y_points_unused, y_plusminus_unused = self.prepare_features(target_data)
        X_pred_points = X_pred['points']  # Now X_pred is properly unpacked dictionary
        X_pred_plusminus = X_pred['plusminus']
        
        print(f"  Defensemen with complete feature data: {len(X_pred_points)} observations")
        
        # Apply feature selection for points model
        if self.feature_selector_points is not None:
            X_pred_points = X_pred_points[self.selected_features_points]
        
        # Apply feature selection for plus/minus model
        if self.feature_selector_plusminus is not None:
            X_pred_plusminus = X_pred_plusminus[self.selected_features_plusminus]
        
        # Scale features if needed
        if hasattr(self.scaler_points, 'transform') and self.model_points.__class__.__name__ in ['Ridge', 'Lasso', 'ElasticNet']:
            X_pred_points_final = self.scaler_points.transform(X_pred_points)
        else:
            X_pred_points_final = X_pred_points
        
        if hasattr(self.scaler_plusminus, 'transform') and self.model_plusminus.__class__.__name__ in ['Ridge', 'Lasso', 'ElasticNet']:
            X_pred_plusminus_final = self.scaler_plusminus.transform(X_pred_plusminus)
        else:
            X_pred_plusminus_final = X_pred_plusminus
        
        # Make ENHANCED predictions with separate feature sets
        predicted_ppg = self.model_points.predict(X_pred_points_final)
        predicted_pm_pg = self.model_plusminus.predict(X_pred_plusminus_final)
        
        # Create results dataframe - COMBINE PREDICTIONS
        # Use the index from the points model as the base (both should have same players anyway)
        results_df = target_data.loc[X_pred_points.index].copy()
        results_df['predicted_ppg'] = predicted_ppg
        results_df['predicted_pm_per_game'] = predicted_pm_pg
        
        # Get actual games played
        results_df['actual_games'] = results_df['games_played'].fillna(0)
        
        # COMPREHENSIVE PREDICTIONS: Points (actual games and 82 games)
        results_df['predicted_points_actual'] = results_df['predicted_ppg'] * results_df['actual_games']
        results_df['predicted_points_82games'] = results_df['predicted_ppg'] * 82
        
        # COMPREHENSIVE PREDICTIONS: Plus/Minus (actual games and 82 games)
        results_df['predicted_pm_actual'] = results_df['predicted_pm_per_game'] * results_df['actual_games']
        results_df['predicted_pm_82games'] = results_df['predicted_pm_per_game'] * 82
        
        # COMPREHENSIVE PREDICTIONS: Combined (actual games and 82 games)
        results_df['predicted_combined_actual'] = results_df['predicted_points_actual'] + results_df['predicted_pm_actual']
        results_df['predicted_combined_82games'] = results_df['predicted_points_82games'] + results_df['predicted_pm_82games']
        
        # ACTUAL VALUES for comparison
        if 'total_points' in results_df.columns:
            results_df['actual_points'] = results_df['total_points']
        else:
            results_df['actual_points'] = results_df.get('goals', 0) + results_df.get('assists', 0)
        
        if 'total_plus_minus' in results_df.columns:
            results_df['actual_pm'] = results_df['total_plus_minus']
        else:
            results_df['actual_pm'] = 0
        
        results_df['actual_combined'] = results_df['actual_points'] + results_df['actual_pm']
        
        # Sort by combined score (82 games) for ranking
        results_df = results_df.sort_values('predicted_combined_82games', ascending=False)
        
        # Return comprehensive columns
        return_cols = ['player_name', 'actual_games',
                      'predicted_points_actual', 'predicted_points_82games', 
                      'predicted_pm_actual', 'predicted_pm_82games',
                      'predicted_combined_actual', 'predicted_combined_82games',
                      'actual_points', 'actual_pm', 'actual_combined']
        
        # Check if player_name column exists
        if 'player_name' not in results_df.columns:
            # Try other possible name columns
            name_cols = ['player_name', 'playerName', 'name', 'full_name', 'fullName']
            name_col_found = None
            for col in name_cols:
                if col in results_df.columns:
                    results_df['player_name'] = results_df[col]
                    name_col_found = col
                    break
            
            if name_col_found is None:
                # Create a placeholder name using player_id if available
                if 'player_id' in results_df.columns:
                    results_df['player_name'] = 'Player_' + results_df['player_id'].astype(str)
                else:
                    # Last resort: use index
                    results_df['player_name'] = 'Player_' + results_df.index.astype(str)
                print(f"  Warning: No player name column found, created placeholder names")
        
        # Ensure all required columns exist
        for col in return_cols:
            if col not in results_df.columns:
                print(f"  Warning: Column {col} not found in results")
        
        return results_df[return_cols].reset_index(drop=True)

