    def _train_single_model(self, X: pd.DataFrame, y: pd.Series, model_type: str, target_name: str) -> Dict[str, Any]:
        """Train a single model - ENHANCED for plus/minus in v1.4."""
        enhanced_label = "ENHANCED " if target_name == 'plusminus' else ""
        feature_type = "lagged+team" if target_name == 'plusminus' else "lagged-only"
        print(f"    Training {enhanced_label}{target_name} model ({feature_type})...")
        
        # Feature selection with ENHANCED approach for plus/minus
        if self.use_feature_selection and len(X.columns) > 20:
            if target_name == 'points':
                k_features = min(40, max(12, len(X.columns) // 4))
            else:  # ENHANCED plus/minus feature selection
                k_features = min(60, max(25, len(X.columns) // 3))  # More features for plus/minus with team context
                
            feature_selector = SelectKBest(score_func=f_regression, k=k_features)
            X_selected = feature_selector.fit_transform(X, y)
            selected_features = X.columns[feature_selector.get_support()].tolist()
            X = pd.DataFrame(X_selected, columns=selected_features, index=X.index)
            
            # Store feature selector
            if target_name == 'points':
                self.feature_selector_points = feature_selector
                self.selected_features_points = selected_features
            else:
                self.feature_selector_plusminus = feature_selector
                self.selected_features_plusminus = selected_features
            
            print(f"    Selected {len(selected_features)} features for {enhanced_label}{target_name} ({feature_type})")
        else:
            if target_name == 'points':
                self.selected_features_points = list(X.columns)
            else:
                self.selected_features_plusminus = list(X.columns)
        
        # Split data
        test_size = min(0.25, max(0.15, 40/len(X)))
        X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=test_size, random_state=42)
        
        # Get ENHANCED model configuration
        models = self._get_enhanced_models(target_name)
        if model_type not in models:
            raise ValueError(f"Unknown model type: {model_type}")
        
        model_config = models[model_type]
        
        # Scale features for linear models
        scaler = self.scaler_points if target_name == 'points' else self.scaler_plusminus
        
        if model_type in ['ridge', 'lasso', 'elastic_net']:
            X_train_scaled = scaler.fit_transform(X_train)
            X_test_scaled = scaler.transform(X_test)
            X_train_final = X_train_scaled
            X_test_final = X_test_scaled
        else:
            X_train_final = X_train
            X_test_final = X_test
        
        # ENHANCED hyperparameter tuning for plus/minus
        cv_folds = min(5, max(3, len(X_train) // 30))
        
        if model_config['search_type'] == 'randomized':
            n_iter = model_config.get('n_iter', 10)
            if target_name == 'plusminus':
                n_iter = n_iter + 5  # More iterations for plus/minus
                
            search = RandomizedSearchCV(
                estimator=model_config['model'],
                param_distributions=model_config['params'],
                n_iter=n_iter,
                cv=cv_folds,
                scoring='r2',
                n_jobs=-1,
                random_state=42
            )
        else:
            search = GridSearchCV(
                estimator=model_config['model'],
                param_grid=model_config['params'],
                cv=cv_folds,
                scoring='r2',
                n_jobs=-1
            )
        
        search.fit(X_train_final, y_train)
        
        # Store model
        if target_name == 'points':
            self.model_points = search.best_estimator_
            self.best_params_points = search.best_params_
        else:
            self.model_plusminus = search.best_estimator_
            self.best_params_plusminus = search.best_params_
        
        # Predictions and metrics
        y_pred = search.best_estimator_.predict(X_test_final)
        
        mae = mean_absolute_error(y_test, y_pred)
        mse = mean_squared_error(y_test, y_pred)
        rmse = np.sqrt(mse)
        r2 = r2_score(y_test, y_pred)
        
        train_score = search.best_estimator_.score(X_train_final, y_train)
        test_score = r2
        overfitting_ratio = (train_score - test_score) / train_score if train_score > 0 else 0
        
        results = {
            'mae': mae, 'mse': mse, 'rmse': rmse, 'r2': r2,
            'train_r2': train_score, 'test_r2': test_score,
            'overfitting_ratio': overfitting_ratio,
            'cv_mean': search.best_score_,
            'y_test': y_test, 'y_pred': y_pred,
            'model_type': model_type,
            'target_name': target_name,
            'best_params': search.best_params_,
            'n_train': len(X_train), 'n_test': len(X_test),
            'n_features_selected': len(X.columns),
            'feature_type': feature_type
        }
        
        print(f"    {enhanced_label}{target_name} model ({feature_type}) - R²: {r2:.3f}, RMSE: {rmse:.4f}")
        return results
    
