        team_features = self._identify_team_features(df)
        
        # NEW v1.4: Team goal differential features
        team_goal_features = ['team_goal_differential', 'team_goals_for_per_game', 'team_goals_against_per_game',
                             'team_goal_diff_per_game', 'strong_offensive_team', 'strong_defensive_team', 'elite_team']
        
        # Experience features to lag
        experience_features = ['years_played', 'years_played_squared', 'years_played_cubed']
        
        # Combine all features for lagging
        all_lag_features = individual_features + pp_features + team_features + team_goal_features + experience_features
        existing_features = [f for f in all_lag_features if f in df.columns]
        
        print(f"\nCreating {self.lag_years}-year lags for {len(existing_features)} defensemen features (ENHANCED v1.4):")
        print(f"  Individual stats: {len([f for f in existing_features if f in individual_features])}")
