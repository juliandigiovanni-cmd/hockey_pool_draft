    def _create_team_goal_differential(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        NEW v1.4: Create team goal differential features (goals_for - goals_against).
        
        Args:
            df: DataFrame with team statistics
            
        Returns:
            DataFrame with team goal differential features added
        """
        print("\nNEW v1.4: Creating team goal differential features...")
        
        # Look for goals for and goals against columns
        goals_for_cols = ['goals_for', 'goalsFor', 'goals_for_team', 'gf', 'GF']
        goals_against_cols = ['goals_against', 'goalsAgainst', 'goals_against_team', 'ga', 'GA']
        
        goals_for_col = goals_against_col = None
        
        for col in goals_for_cols:
            if col in df.columns:
                goals_for_col = col
                break
        
        for col in goals_against_cols:
            if col in df.columns:
                goals_against_col = col
                break
        
        if goals_for_col and goals_against_col:
            # Create team goal differential
            df['team_goal_differential'] = df[goals_for_col].fillna(0) - df[goals_against_col].fillna(0)
            
            # Create additional team strength metrics
            df['team_goals_for_per_game'] = df[goals_for_col].fillna(0) / df.get('games_played_team', df.get('games_played', 82)).replace(0, 82)
            df['team_goals_against_per_game'] = df[goals_against_col].fillna(0) / df.get('games_played_team', df.get('games_played', 82)).replace(0, 82)
            df['team_goal_diff_per_game'] = df['team_goal_differential'] / df.get('games_played_team', df.get('games_played', 82)).replace(0, 82)
            
            # Team strength indicators
            df['strong_offensive_team'] = (df['team_goals_for_per_game'] > df['team_goals_for_per_game'].quantile(0.75)).astype(int)
            df['strong_defensive_team'] = (df['team_goals_against_per_game'] < df['team_goals_against_per_game'].quantile(0.25)).astype(int)
            df['elite_team'] = ((df['team_goal_diff_per_game'] > df['team_goal_diff_per_game'].quantile(0.8)) & 
                               (df['team_goals_for_per_game'] > df['team_goals_for_per_game'].median())).astype(int)
            
            print(f"  Team goal differential statistics:")
            print(f"    Mean: {df['team_goal_differential'].mean():.1f}")
            print(f"    Range: {df['team_goal_differential'].min():.0f} to {df['team_goal_differential'].max():.0f}")
            print(f"    Strong offensive teams: {df['strong_offensive_team'].sum()} observations")
            print(f"    Strong defensive teams: {df['strong_defensive_team'].sum()} observations")
            print(f"    Elite teams: {df['elite_team'].sum()} observations")
            
        else:
            print(f"  Warning: Could not find goals for/against columns")
            print(f"  Available columns: {[col for col in df.columns if 'goal' in col.lower()]}")
            # Create placeholder features
            df['team_goal_differential'] = 0
            df['team_goals_for_per_game'] = 3.0
            df['team_goals_against_per_game'] = 3.0  
            df['team_goal_diff_per_game'] = 0
            df['strong_offensive_team'] = 0
            df['strong_defensive_team'] = 0
            df['elite_team'] = 0
        
        return df
    
    def _create_dual_targets(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Create dual target variables: points per game and plus/minus per game.
        ENHANCED: Better plus/minus data handling.
        
        Args:
            df: DataFrame with player statistics
            
        Returns:
            DataFrame with dual target variables for defensemen
        """
        print("\nCreating dual target variables for defensemen (enhanced v1.4)...")
        
        # Create points per game target
        if 'points_player' in df.columns:
            df['total_points'] = df['points_player'].fillna(0)
            print("Using 'points_player' column for points calculation")
        elif 'goals' in df.columns and 'assists' in df.columns:
            df['total_points'] = df['goals'].fillna(0) + df['assists'].fillna(0)
            print("Calculating points from goals + assists")
        else:
            raise ValueError("Cannot find points_player column or goals+assists columns")
        
        # Handle games played column variations
        games_played_cols = ['games_played_player', 'games_played', 'gamesPlayed', 'GP', 'Games', 'games']
        games_played_col = None
        
        for col in games_played_cols:
            if col in df.columns:
                games_played_col = col
                break
        
        if games_played_col:
            df['games_played'] = df[games_played_col].fillna(0).clip(lower=0)
        else:
            raise ValueError(f"Cannot find games played column. Available columns: {list(df.columns)}")
        
        # Create points per game
        valid_games_mask = df['games_played'] > 0
        df.loc[valid_games_mask, 'points_per_game'] = (
            df.loc[valid_games_mask, 'total_points'] / df.loc[valid_games_mask, 'games_played']
        )
        df.loc[~valid_games_mask, 'points_per_game'] = 0
        
        # Create plus/minus per game target - ENHANCED HANDLING FOR v1.4
        plusminus_cols = ['plus_minus', 'plusMinus', 'plus_minus_player', 'pm', 'PM']
        plusminus_col = None
        
        for col in plusminus_cols:
            if col in df.columns:
                plusminus_col = col
                break
        
        if plusminus_col:
            # ENHANCED: Preserve original plus/minus values - minimal processing
            print(f"Using '{plusminus_col}' column for plus/minus calculation (preserving full signal)")
            df['total_plus_minus'] = pd.to_numeric(df[plusminus_col], errors='coerce')
            
            # Check for extreme values that might be data errors (not defensive performance)
            pm_stats_raw = df['total_plus_minus'].describe()
            print(f"Raw plus/minus statistics: min={pm_stats_raw['min']:.1f}, max={pm_stats_raw['max']:.1f}, std={pm_stats_raw['std']:.1f}")
            
            # Only fix obvious data errors (like values > 200 or < -200 in a single season)
            extreme_mask = (df['total_plus_minus'].abs() > 200) & df['total_plus_minus'].notna()
            if extreme_mask.any():
                print(f"Found {extreme_mask.sum()} extreme plus/minus values (>200 or <-200) - likely data errors")
                df.loc[extreme_mask, 'total_plus_minus'] = np.nan
            
            # Fill only missing values
            df['total_plus_minus'] = df['total_plus_minus'].fillna(0)
        else:
            print("Warning: No plus/minus column found - creating placeholder")
            df['total_plus_minus'] = 0
        
        # Create plus/minus per game - PRESERVE ALL SIGNAL
        df.loc[valid_games_mask, 'plus_minus_per_game'] = (
            df.loc[valid_games_mask, 'total_plus_minus'] / df.loc[valid_games_mask, 'games_played']
        )
        df.loc[~valid_games_mask, 'plus_minus_per_game'] = 0
        
        # Statistics for both targets
        ppg_stats = df[df['points_per_game'] > 0]['points_per_game'].describe()
        pm_stats = df['plus_minus_per_game'].describe()
        
        print(f"Points per game statistics (defensemen):")
        print(f"  Mean: {ppg_stats['mean']:.3f}")
        print(f"  Median: {ppg_stats['50%']:.3f}")
        print(f"  Max: {ppg_stats['max']:.3f}")
        
        print(f"Plus/minus per game statistics (defensemen, ENHANCED):")
        print(f"  Mean: {pm_stats['mean']:.3f}")
        print(f"  Median: {pm_stats['50%']:.3f}")
        print(f"  Range: {pm_stats['min']:.3f} to {pm_stats['max']:.3f}")
        print(f"  Std Dev: {pm_stats['std']:.3f}")
        print(f"  Non-zero observations: {(df['plus_minus_per_game'] != 0).sum()}")
        
        return df
    
