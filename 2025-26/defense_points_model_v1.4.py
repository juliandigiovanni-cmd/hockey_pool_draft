    def engineer_features(self, df: pd.DataFrame) -> pd.DataFrame:
        """ENHANCED feature engineering for defensemen with improved plus/minus focus."""
        print(f"\nENHANCED feature engineering for defensemen (v1.4)...")
        
        df_eng = df.copy()
        
        # Find all lag columns
        lag_columns = [col for col in df_eng.columns if 'lag' in col]
        
        if lag_columns:
            print(f"Found {len(lag_columns)} lag columns for ENHANCED defensemen feature engineering")
            
            # Get base features that have lags
            base_features = list(set([col.replace('_lag1', '').replace('_lag2', '').replace('_lag3', '') 
                                    for col in lag_columns]))
            
            print(f"Engineering features for {len(base_features)} base defensemen features")
            
            # Standard lag-based features
            for base_feature in base_features:
                lag_cols = [col for col in lag_columns if col.startswith(f'{base_feature}_lag')]
                
                if lag_cols:
                    # Historical averages
                    df_eng[f'{base_feature}_hist_avg'] = df_eng[lag_cols].mean(axis=1, skipna=True)
                    
                    # Historical consistency (if multiple lags)
                    if len(lag_cols) >= 2:
                        df_eng[f'{base_feature}_hist_std'] = df_eng[lag_cols].std(axis=1, skipna=True).fillna(0)
                    
                    # Recent trends
                    if len(lag_cols) >= 2:
                        if f'{base_feature}_lag1' in df_eng.columns and f'{base_feature}_lag2' in df_eng.columns:
                            trend = df_eng[f'{base_feature}_lag1'] - df_eng[f'{base_feature}_lag2']
                            df_eng[f'{base_feature}_trend'] = trend.fillna(0)
            
            # ENHANCED defensemen-specific feature engineering for v1.4
            self._create_enhanced_defensive_interactions(df_eng, lag_columns)
            self._create_enhanced_team_context_features(df_eng, lag_columns)
            self._create_covid_interactions(df_eng, lag_columns)
            self._create_career_trajectory_features(df_eng)
            
            # NEW v1.4: Create teammate quality features
            df_eng = self._create_teammate_quality_features(df_eng)
        
        # Create ENHANCED defensive-specific per-game rates
        for lag in range(1, min(self.lag_years + 1, 3)):
            if f'goals_lag{lag}' in df_eng.columns and f'games_played_lag{lag}' in df_eng.columns:
                goals_per_game = df_eng[f'goals_lag{lag}'] / df_eng[f'games_played_lag{lag}'].replace(0, np.nan)
                df_eng[f'goals_per_game_lag{lag}'] = goals_per_game.fillna(0)
                
            if f'assists_lag{lag}' in df_eng.columns and f'games_played_lag{lag}' in df_eng.columns:
                assists_per_game = df_eng[f'assists_lag{lag}'] / df_eng[f'games_played_lag{lag}'].replace(0, np.nan)
                df_eng[f'assists_per_game_lag{lag}'] = assists_per_game.fillna(0)
            
            # ENHANCED: Plus/minus rate (critical for defensemen)
            if f'total_plus_minus_lag{lag}' in df_eng.columns and f'games_played_lag{lag}' in df_eng.columns:
                pm_per_game = df_eng[f'total_plus_minus_lag{lag}'] / df_eng[f'games_played_lag{lag}'].replace(0, np.nan)
                df_eng[f'pm_per_game_lag{lag}'] = pm_per_game.fillna(0)
            
            # ENHANCED: Defensive efficiency ratios
            if f'assists_lag{lag}' in df_eng.columns and f'goals_lag{lag}' in df_eng.columns:
                total_points_lag = df_eng[f'assists_lag{lag}'] + df_eng[f'goals_lag{lag}']
                assist_ratio = df_eng[f'assists_lag{lag}'] / total_points_lag.replace(0, np.nan)
                df_eng[f'defensive_assist_ratio_lag{lag}'] = assist_ratio.fillna(0.5)  # Defensemen typically have more assists
        
        # Clean up infinite and extreme values
        df_eng = df_eng.replace([np.inf, -np.inf], np.nan)
        
        # Fill remaining NaN values
        numeric_cols = df_eng.select_dtypes(include=[np.number]).columns
        df_eng[numeric_cols] = df_eng[numeric_cols].fillna(0)
        
        print(f"Final ENHANCED defensemen data shape: {df_eng.shape}")
        
        return df_eng
    
