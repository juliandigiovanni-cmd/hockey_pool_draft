    def _get_numeric_features(self, df: pd.DataFrame, potential_features: List[str]) -> List[str]:
        """Helper method to identify numeric features."""
        numeric_features = []
        for col in potential_features:
            if col in df.columns:
                try:
                    pd.to_numeric(df[col], errors='raise')
                    numeric_features.append(col)
                except (ValueError, TypeError):
                    try:
                        pd.to_numeric(df[col], errors='coerce')
                        numeric_features.append(col)
                        print(f"      Converting '{col}' to numeric")
                    except:
                        print(f"      Excluding non-numeric column: '{col}'")
        return numeric_features
    
    def _remove_high_missing_features(self, df: pd.DataFrame, numeric_features: List[str]) -> List[str]:
        """Helper method to remove features with excessive missing data."""
        good_features = []
        for col in numeric_features:
            missing_pct = df[col].isnull().sum() / len(df) * 100
            if missing_pct <= 70:
                good_features.append(col)
            else:
                print(f"      Excluding '{col}' due to {missing_pct:.1f}% missing data")
        return good_features
    
    def _finalize_feature_preparation(self, X: pd.DataFrame, y_points: pd.Series, y_plusminus: pd.Series, model_name: str) -> Tuple[pd.DataFrame, pd.Series, pd.Series]:
        """Helper method to finalize feature preparation for both models."""
        print(f"    Before missing data removal ({model_name}): {len(X)} observations")
        
        # Force conversion to numeric
        for col in X.columns:
            X[col] = pd.to_numeric(X[col], errors='coerce')
        
        # Handle missing data
        core_features = [f for f in X.columns if any(core in f for core in ['goals_lag', 'assists_lag', 'plus_minus_lag'])]
        
        if core_features:
            missing_mask = X[core_features].isnull().all(axis=1) | y_points.isnull() | y_plusminus.isnull()
        else:
            missing_mask = X.isnull().all(axis=1) | y_points.isnull() | y_plusminus.isnull()
        
        if missing_mask.any():
            X_clean = X[~missing_mask]
            y_points_clean = y_points[~missing_mask]
            y_plusminus_clean = y_plusminus[~missing_mask]
            print(f"    Removed {missing_mask.sum()} rows with missing core data ({model_name})")
        else:
            X_clean = X
            y_points_clean = y_points
            y_plusminus_clean = y_plusminus
        
        # Fill remaining missing values
        X_clean = X_clean.fillna(0)
        
        print(f"    After missing data handling ({model_name}): {len(X_clean)} observations")
        print(f"    Final {model_name} feature matrix shape: {X_clean.shape}")
        
        # Feature breakdown for this model
        self._print_feature_breakdown(X_clean.columns, model_name)
        
        return X_clean, y_points_clean, y_plusminus_clean
    
