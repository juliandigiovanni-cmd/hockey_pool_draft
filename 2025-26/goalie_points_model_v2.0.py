    def predict_season_with_point_ranking(self, df_full: pd.DataFrame, target_year: int) -> pd.DataFrame:
        """
        Predict all four targets and calculate point-based rankings.
        
        Args:
            df_full: Complete dataset including target year
            target_year: Year to predict
            
        Returns:
            DataFrame with comprehensive predictions and point-based rankings
        """
        if not all([self.model_wins, self.model_shutouts, self.model_gaa, self.model_save_pct]):
            print("Warning: Not all models are trained. Available models:")
            print(f"  Wins: {'✓' if self.model_wins else '✗'}")
            print(f"  Shutouts: {'✓' if self.model_shutouts else '✗'}")
            print(f"  GAA: {'✓' if self.model_gaa else '✗'}")
            print(f"  Save Pct: {'✓' if self.model_save_pct else '✗'}")
        
        # Get target year data
        target_data = df_full[df_full['year'] == target_year].copy()
        
        if len(target_data) == 0:
            raise ValueError(f"No goalie data found for year {target_year}")
        
        print(f"\nPredicting {target_year} season for goalies with POINT-BASED RANKING:")
        print(f"  Goalies to predict: {len(target_data)}")
        
        # Prepare features for each model
        feature_matrices, _ = self.prepare_features_quadruple(target_data)
        
        # Make predictions for each target
        predictions = {}
        
        # 1. Wins predictions
        if self.model_wins and len(feature_matrices['wins']) > 0:
            X_wins = feature_matrices['wins']
            if self.feature_selector_wins is not None:
                X_wins = X_wins[self.selected_features_wins]
            
            if hasattr(self.scaler_wins, 'transform') and self.model_wins.__class__.__name__ in ['Ridge', 'Lasso', 'ElasticNet']:
                X_wins_final = self.scaler_wins.transform(X_wins)
            else:
                X_wins_final = X_wins
            
            predictions['wins_per_game'] = self.model_wins.predict(X_wins_final)
        else:
            predictions['wins_per_game'] = np.zeros(len(target_data))
        
        # 2. Shutouts predictions
        if self.model_shutouts and len(feature_matrices['shutouts']) > 0:
            X_shutouts = feature_matrices['shutouts']
            if self.feature_selector_shutouts is not None:
                X_shutouts = X_shutouts[self.selected_features_shutouts]
            
            if hasattr(self.scaler_shutouts, 'transform') and self.model_shutouts.__class__.__name__ in ['Ridge', 'Lasso', 'ElasticNet']:
                X_shutouts_final = self.scaler_shutouts.transform(X_shutouts)
            else:
                X_shutouts_final = X_shutouts
            
            predictions['shutouts_per_game'] = self.model_shutouts.predict(X_shutouts_final)
        else:
            predictions['shutouts_per_game'] = np.zeros(len(target_data))
        
        # 3. GAA predictions (40+ games only)
        if self.model_gaa and len(feature_matrices['gaa']) > 0:
            gaa_data = target_data[target_data['games_played_player'] >= 40]  # Fixed: use games_played_player
            if len(gaa_data) > 0:
                X_gaa = feature_matrices['gaa']
                if self.feature_selector_gaa is not None:
                    X_gaa = X_gaa[self.selected_features_gaa]
                
                if hasattr(self.scaler_gaa, 'transform') and self.model_gaa.__class__.__name__ in ['Ridge', 'Lasso', 'ElasticNet']:
                    X_gaa_final = self.scaler_gaa.transform(X_gaa)
                else:
                    X_gaa_final = X_gaa
                
                gaa_predictions = self.model_gaa.predict(X_gaa_final)
                
                # Map back to full dataset
                predictions['gaa'] = np.full(len(target_data), np.nan)
                predictions['gaa'][target_data['games_played_player'] >= 40] = gaa_predictions  # Fixed: use games_played_player
            else:
                predictions['gaa'] = np.full(len(target_data), np.nan)
        else:
            predictions['gaa'] = np.full(len(target_data), np.nan)
        
        # 4. Save Percentage predictions (40+ games only)
        if self.model_save_pct and len(feature_matrices['save_pct']) > 0:
            save_pct_data = target_data[target_data['games_played_player'] >= 40]  # Fixed: use games_played_player
            if len(save_pct_data) > 0:
                X_save_pct = feature_matrices['save_pct']
                if self.feature_selector_save_pct is not None:
                    X_save_pct = X_save_pct[self.selected_features_save_pct]
                
                if hasattr(self.scaler_save_pct, 'transform') and self.model_save_pct.__class__.__name__ in ['Ridge', 'Lasso', 'ElasticNet']:
                    X_save_pct_final = self.scaler_save_pct.transform(X_save_pct)
                else:
                    X_save_pct_final = X_save_pct
                
                save_pct_predictions = self.model_save_pct.predict(X_save_pct_final)
                
                # Map back to full dataset
                predictions['save_pct'] = np.full(len(target_data), np.nan)
                predictions['save_pct'][target_data['games_played_player'] >= 40] = save_pct_predictions  # Fixed: use games_played_player
            else:
                predictions['save_pct'] = np.full(len(target_data), np.nan)
        else:
            predictions['save_pct'] = np.full(len(target_data), np.nan)
        
        # Create results dataframe
        results_df = target_data.copy()
        
        # Add predictions
        results_df['predicted_wins_per_game'] = predictions['wins_per_game']
        results_df['predicted_shutouts_per_game'] = predictions['shutouts_per_game']
        results_df['predicted_gaa'] = predictions['gaa']
        results_df['predicted_save_pct'] = predictions['save_pct']
        
        # Calculate point-based rankings
        results_df = self._calculate_point_rankings(results_df)
        
        return results_df
    
    def _calculate_point_rankings(self, results_df: pd.DataFrame) -> pd.DataFrame:
        """
        Calculate point-based rankings according to the specified system.
        
        Ranking System:
        - Each win = 1 point
        - Each shutout win = 3 points (no double counting)
        - Best GAA (40+ games) = 10 points
        - Best Save Percentage (40+ games) = 10 points
        """
        print("  Calculating POINT-BASED RANKINGS...")
        
        # Get actual games played - use games_played_player consistently
        results_df['actual_games'] = results_df['games_played_player'].fillna(0)  # Fixed: use games_played_player
        
        # Calculate predictions for actual games and 82 games
        results_df['predicted_wins_actual'] = results_df['predicted_wins_per_game'] * results_df['actual_games']
        results_df['predicted_wins_82games'] = results_df['predicted_wins_per_game'] * 82
        
        results_df['predicted_shutouts_actual'] = results_df['predicted_shutouts_per_game'] * results_df['actual_games']
        results_df['predicted_shutouts_82games'] = results_df['predicted_shutouts_per_game'] * 82
        
        # Calculate points for actual games
        self._calculate_points_for_scenario(results_df, 'actual')
        
        # Calculate points for 82 games
        self._calculate_points_for_scenario(results_df, '82games')
        
        # Get actual values for comparison
        if 'total_wins' in results_df.columns:
            results_df['actual_wins'] = results_df['total_wins']
        else:
            results_df['actual_wins'] = 0
        
        if 'total_shutouts' in results_df.columns:
            results_df['actual_shutouts'] = results_df['total_shutouts']
        else:
            results_df['actual_shutouts'] = 0
        
        if 'goals_against_average' in results_df.columns:
            results_df['actual_gaa'] = results_df['goals_against_average']
        else:
            results_df['actual_gaa'] = np.nan
        
        if 'save_percentage' in results_df.columns:
            results_df['actual_save_pct'] = results_df['save_percentage']
        else:
            results_df['actual_save_pct'] = np.nan
        
        # Calculate actual points
        self._calculate_actual_points(results_df)
        
        # Sort by total points (82 games)
        results_df = results_df.sort_values('total_points_82games', ascending=False)
        
        return results_df
    
    def _calculate_points_for_scenario(self, results_df: pd.DataFrame, scenario: str) -> None:
        """Calculate points for a specific scenario (actual or 82games)."""
        print(f"    Calculating points for {scenario} scenario...")
        
        wins_col = f'predicted_wins_{scenario}'
        shutouts_col = f'predicted_shutouts_{scenario}'
        
        # 1. Points from wins (1 point each)
        results_df[f'points_from_wins_{scenario}'] = results_df[wins_col].clip(lower=0)
        
        # 2. Points from shutout wins (3 points each, no double counting)
        # Shutout wins should be subtracted from regular wins to avoid double counting
        results_df[f'non_shutout_wins_{scenario}'] = (results_df[wins_col] - results_df[shutouts_col]).clip(lower=0)
        results_df[f'points_from_non_shutout_wins_{scenario}'] = results_df[f'non_shutout_wins_{scenario}'] * 1
        results_df[f'points_from_shutouts_{scenario}'] = results_df[shutouts_col].clip(lower=0) * 3
        
        # 3. Points from best GAA (10 points for best among 40+ games)
        qualified_for_gaa = results_df['actual_games'] >= 40 if scenario == 'actual' else results_df['actual_games'] >= 40  # Use actual_games consistently
        gaa_qualified = results_df[qualified_for_gaa & results_df['predicted_gaa'].notna()]
        
        results_df[f'points_from_gaa_{scenario}'] = 0
        if len(gaa_qualified) > 0:
            best_gaa_idx = gaa_qualified['predicted_gaa'].idxmin()  # Lowest GAA is best
            results_df.loc[best_gaa_idx, f'points_from_gaa_{scenario}'] = 10
            print(f"      Best GAA ({scenario}): {results_df.loc[best_gaa_idx, 'predicted_gaa']:.3f}")
        
        # 4. Points from best save percentage (10 points for best among 40+ games)
        save_pct_qualified = results_df[qualified_for_gaa & results_df['predicted_save_pct'].notna()]
        
        results_df[f'points_from_save_pct_{scenario}'] = 0
        if len(save_pct_qualified) > 0:
            best_save_pct_idx = save_pct_qualified['predicted_save_pct'].idxmax()  # Highest save % is best
            results_df.loc[best_save_pct_idx, f'points_from_save_pct_{scenario}'] = 10
            print(f"      Best Save %% ({scenario}): {results_df.loc[best_save_pct_idx, 'predicted_save_pct']:.3f}")
        
        # Calculate total points
        results_df[f'total_points_{scenario}'] = (
            results_df[f'points_from_non_shutout_wins_{scenario}'] +
            results_df[f'points_from_shutouts_{scenario}'] +
            results_df[f'points_from_gaa_{scenario}'] +
            results_df[f'points_from_save_pct_{scenario}']
        )
        
        print(f"    Total points calculated for {scenario}")
    
    def _calculate_actual_points(self, results_df: pd.DataFrame) -> None:
        """Calculate points based on actual performance."""
        print("    Calculating actual performance points...")
        
        # 1. Points from actual wins
        results_df['actual_points_from_wins'] = results_df['actual_wins'].clip(lower=0)
        
        # 2. Points from actual shutouts (no double counting)
        results_df['actual_non_shutout_wins'] = (results_df['actual_wins'] - results_df['actual_shutouts']).clip(lower=0)
        results_df['actual_points_from_non_shutout_wins'] = results_df['actual_non_shutout_wins'] * 1
        results_df['actual_points_from_shutouts'] = results_df['actual_shutouts'].clip(lower=0) * 3
        
        # 3. Points from best actual GAA (40+ games)
        qualified_actual = results_df[
            (results_df['actual_games'] >= 40) & 
            results_df['actual_gaa'].notna() & 
            (results_df['actual_gaa'] > 0)
        ]
        
        results_df['actual_points_from_gaa'] = 0
        if len(qualified_actual) > 0:
            best_actual_gaa_idx = qualified_actual['actual_gaa'].idxmin()
            results_df.loc[best_actual_gaa_idx, 'actual_points_from_gaa'] = 10
            print(f"      Best Actual GAA: {results_df.loc[best_actual_gaa_idx, 'actual_gaa']:.3f}")
        
        # 4. Points from best actual save percentage (40+ games)
        save_pct_qualified_actual = results_df[
            (results_df['actual_games'] >= 40) & 
            results_df['actual_save_pct'].notna() & 
            (results_df['actual_save_pct'] > 0)
        ]
        
        results_df['actual_points_from_save_pct'] = 0
        if len(save_pct_qualified_actual) > 0:
            best_actual_save_pct_idx = save_pct_qualified_actual['actual_save_pct'].idxmax()
            results_df.loc[best_actual_save_pct_idx, 'actual_points_from_save_pct'] = 10
            print(f"      Best Actual Save %%: {results_df.loc[best_actual_save_pct_idx, 'actual_save_pct']:.3f}")
        
        # Calculate total actual points
        results_df['actual_total_points'] = (
            results_df['actual_points_from_non_shutout_wins'] +
            results_df['actual_points_from_shutouts'] +
            results_df['actual_points_from_gaa'] +
            results_df['actual_points_from_save_pct']
        )
    
