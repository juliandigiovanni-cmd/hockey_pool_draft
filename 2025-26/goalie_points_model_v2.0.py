    def _prepare_single_target_features_v2(self, df: pd.DataFrame, exclude_cols: List[str], target_name: str) -> pd.DataFrame:
        """
        VERSION 2.0: Prepare features for a single target with STRICT LAGGED-ONLY exclusions.
        NO contemporaneous variables allowed - only historical (lagged) data.
        
        Args:
            df: DataFrame with features
            exclude_cols: Columns to exclude
            target_name: Name of the target being prepared
            
        Returns:
            Feature matrix for the target using only lagged variables
        """
        print(f"    {target_name.upper()} model: STRICT LAGGED-ONLY feature preparation (v2.0)")
        
        # STRICT v2.0: Additional exclusions for ALL current season variables
        current_season_exclude = []
        
        for col in df.columns:
            # Skip if already in exclude list or is a lag variable or engineered feature
            if col in exclude_cols or 'lag' in col or any(keep in col for keep in ['hist', 'trend', 'covid', '_x_', 'rel_team', 'teammate']):
                continue
            
            # STRICT v2.0: Exclude ALL current season variables (individual AND team)
            if any(indicator in col.lower() for indicator in [
                # Individual goalie current season stats
                'wins_player', 'losses_player', 'ot_losses', 'saves', 'shots_against', 
                'goals_against_player', 'goals_against_avg', 'save_pct', 'shutouts',
                'games_played_player', 'games_started', 'time_on_ice', 'goals', 'assists', 
                'points_player', 'penalty_minutes',
                # STRICT v2.0: ALL team current season variables excluded
                'wins', 'losses', 'ties', 'otl', 'points_pct', 'goals_for', 'goals_against',
                'goal_differential', 'goals_for_per_game', 'goals_against_per_game',
                'goal_diff_per_game', 'offensive_team', 'defensive_team', 'elite_team',
                # Additional team stats to exclude
                'pp_', 'pk_', 'sv_', 'gf_', 'ga_', 'diff', 'streak', 'home_', 'away_',
                'last_10', 'percent', 'rate', 'avg', 'faceoff'
            ]):
                current_season_exclude.append(col)
        
        print(f"    Excluded {len(current_season_exclude)} current season variables (STRICT v2.0)")
        
        # Exclude text/name columns
        name_indicators = ['name', 'player', 'firstname', 'lastname', 'full_name', 'player_name']
        for col in df.columns:
            if any(indicator in col.lower() for indicator in name_indicators):
                current_season_exclude.append(col)
        
        # Combine all exclusions
        all_exclude_cols = list(set(exclude_cols + current_season_exclude))
        potential_features = [col for col in df.columns if col not in all_exclude_cols]
        
        # Keep only numeric features
        numeric_features = []
        for col in potential_features:
            if col in df.columns:
                try:
                    pd.to_numeric(df[col], errors='raise')
                    numeric_features.append(col)
                except:
                    try:
                        pd.to_numeric(df[col], errors='coerce')
                        numeric_features.append(col)
                    except:
                        pass
        
        # Remove features with excessive missing data
        good_features = []
        for col in numeric_features:
            missing_pct = df[col].isnull().sum() / len(df) * 100
            if missing_pct <= 70:
                good_features.append(col)
        
        print(f"    {target_name.upper()} model final feature count: {len(good_features)} (LAGGED-ONLY)")
        
        # Count feature types for verification
        lagged_features = [f for f in good_features if 'lag' in f]
        engineered_features = [f for f in good_features if any(eng in f for eng in ['hist', 'trend', '_x_', 'ratio', 'context'])]
        
        print(f"      Lagged features: {len(lagged_features)}")
        print(f"      Engineered features: {len(engineered_features)}")
        print(f"      Other features: {len(good_features) - len(lagged_features) - len(engineered_features)}")
        
        # Store feature columns for this target
        if target_name == 'wins':
            self.feature_columns_wins = good_features
        elif target_name == 'shutouts':
            self.feature_columns_shutouts = good_features
        elif target_name == 'gaa':
            self.feature_columns_gaa = good_features
        elif target_name == 'save_pct':
            self.feature_columns_save_pct = good_features
        
        # Return feature matrix
        X = df[good_features].copy()
        
        # Force conversion to numeric
        for col in X.columns:
            X[col] = pd.to_numeric(X[col], errors='coerce')
        
        # Fill missing values
        X = X.fillna(0)
        
        return X
    
