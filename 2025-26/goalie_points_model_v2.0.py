    def get_quadruple_feature_importance(self, top_n: int = 20) -> Dict[str, pd.DataFrame]:
        """
        Get feature importance analysis for all four goalie models.
        
        Args:
            top_n: Number of top features to return for each model
            
        Returns:
            Dictionary with feature importance DataFrames for each model
        """
        results = {}
        
        model_info = [
            ('wins', self.model_wins, self.selected_features_wins),
            ('shutouts', self.model_shutouts, self.selected_features_shutouts),
            ('gaa', self.model_gaa, self.selected_features_gaa),
            ('save_pct', self.model_save_pct, self.selected_features_save_pct)
        ]
        
        for model_name, model, features in model_info:
            if model is not None and features is not None:
                results[model_name] = self._get_single_goalie_importance(
                    model, features, model_name, top_n
                )
            else:
                print(f"Skipping feature importance for {model_name}: model not available")
        
        return results
    
    def _get_single_goalie_importance(self, model, feature_names, model_name, top_n):
        """Get feature importance for a single goalie model."""
        # Get importance values
        if hasattr(model, 'feature_importances_'):
            importance = model.feature_importances_
        else:
            importance = np.abs(model.coef_)
        
        importance_df = pd.DataFrame({
            'feature': feature_names,
            'importance': importance,
            'model': model_name
        }).sort_values('importance', ascending=False)
        
        # Categorize goalie-specific features using correct column names
        def categorize_goalie_feature(feature_name):
            if 'covid' in feature_name.lower():
                return "COVID"
            elif 'years_played' in feature_name or 'rookie' in feature_name or 'prime' in feature_name or 'veteran' in feature_name:
                return "EXPERIENCE"
            elif '_x_' in feature_name or 'interaction' in feature_name:
                return "INTERACTION"
            elif any(goalie_stat in feature_name for goalie_stat in ['wins_player', 'wins_per_game', 'shutouts', 'goals_against_avg', 'save_pct']):
                return "GOALIE_PERFORMANCE"
            elif any(goalie_stat in feature_name for goalie_stat in ['saves', 'shots_against', 'games_started', 'games_played_player']):
                return "GOALIE_WORKLOAD"
            elif any(goalie_stat in feature_name for goalie_stat in ['losses_player', 'ot_losses_player', 'goals_against_player']):
                return "GOALIE_RESULTS"
            elif 'team_defense' in feature_name or 'defensive' in feature_name:
                return "TEAM_DEFENSE"
            elif 'goal_differential' in feature_name or 'goal_diff' in feature_name:
                return "TEAM_GOAL_DIFF"
            elif 'rel_team' in feature_name or 'context' in feature_name:
                return "TEAM_CONTEXT"
            elif any(team_indicator in feature_name.lower() for team_indicator in ['wins', 'losses', 'goals_for', 'goals_against']):
                return "TEAM_STATS"
            elif feature_name.startswith('pp') or 'power' in feature_name.lower():
                return "SPECIAL_TEAMS"
            elif 'quality' in feature_name or 'elite' in feature_name:
                return "QUALITY_METRICS"
            else:
                return "OTHER"
        
        importance_df['category'] = importance_df['feature'].apply(categorize_goalie_feature)
        
        return importance_df.head(top_n)
    
