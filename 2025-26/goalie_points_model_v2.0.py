    def train_quadruple_models(self, X: Dict[str, pd.DataFrame], targets: Dict[str, pd.Series], 
                              model_type: str = 'random_forest') -> Dict[str, Any]:
        """
        Train quadruple goalie models.
        
        Args:
            X: Dictionary with feature matrices for each target
            targets: Dictionary with target series for each model
            model_type: Type of model to train
            
        Returns:
            Dictionary containing results from all four models
        """
        print(f"\nTraining QUADRUPLE goalie models ({model_type}):")
        
        results = {}
        target_names = ['wins', 'shutouts', 'gaa', 'save_pct']
        
        for target_name in target_names:
            if target_name in X and len(X[target_name]) > 0:
                print(f"  Training {target_name.upper()} model: {X[target_name].shape}")
                results[target_name] = self._train_single_goalie_model(
                    X[target_name], targets[target_name], model_type, target_name
                )
            else:
                print(f"  Skipping {target_name.upper()} model: insufficient data")
                results[target_name] = None
        
        # Combined results summary
        valid_results = {k: v for k, v in results.items() if v is not None}
        if valid_results:
            avg_r2 = np.mean([v['r2'] for v in valid_results.values()])
            results['combined'] = {
                'model_type': model_type,
                'avg_r2': avg_r2,
                'valid_models': list(valid_results.keys()),
                'n_models': len(valid_results)
            }
            
            print(f"\n  QUADRUPLE MODEL SUMMARY:")
            for target_name, result in valid_results.items():
                print(f"    {target_name.upper()} R²: {result['r2']:.3f}, RMSE: {result['rmse']:.4f}")
            print(f"    Average R²: {avg_r2:.3f}")
        
        return results
    
    def _train_single_goalie_model(self, X: pd.DataFrame, y: pd.Series, model_type: str, target_name: str) -> Dict[str, Any]:
        """Train a single goalie model."""
        print(f"    Training {target_name} model...")
        
        # Feature selection
        if self.use_feature_selection and len(X.columns) > 15:
            if target_name in ['gaa', 'save_pct']:
                k_features = min(50, max(20, len(X.columns) // 3))  # More features for precision stats
            else:
                k_features = min(35, max(15, len(X.columns) // 4))  # Standard for wins/shutouts
                
            feature_selector = SelectKBest(score_func=f_regression, k=k_features)
            X_selected = feature_selector.fit_transform(X, y)
            selected_features = X.columns[feature_selector.get_support()].tolist()
            X = pd.DataFrame(X_selected, columns=selected_features, index=X.index)
            
            # Store feature selector
            if target_name == 'wins':
                self.feature_selector_wins = feature_selector
                self.selected_features_wins = selected_features
            elif target_name == 'shutouts':
                self.feature_selector_shutouts = feature_selector
                self.selected_features_shutouts = selected_features
            elif target_name == 'gaa':
                self.feature_selector_gaa = feature_selector
                self.selected_features_gaa = selected_features
            elif target_name == 'save_pct':
                self.feature_selector_save_pct = feature_selector
                self.selected_features_save_pct = selected_features
            
            print(f"    Selected {len(selected_features)} features for {target_name}")
        else:
            if target_name == 'wins':
                self.selected_features_wins = list(X.columns)
            elif target_name == 'shutouts':
                self.selected_features_shutouts = list(X.columns)
            elif target_name == 'gaa':
                self.selected_features_gaa = list(X.columns)
            elif target_name == 'save_pct':
                self.selected_features_save_pct = list(X.columns)
        
        # Split data
        test_size = min(0.25, max(0.15, 20/len(X)))
        X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=test_size, random_state=42)
        
        # Get model configuration
        models = self._get_goalie_models(target_name)
        if model_type not in models:
            raise ValueError(f"Unknown model type: {model_type}")
        
        model_config = models[model_type]
        
        # Scale features for linear models
        if target_name == 'wins':
            scaler = self.scaler_wins
        elif target_name == 'shutouts':
            scaler = self.scaler_shutouts
        elif target_name == 'gaa':
            scaler = self.scaler_gaa
        else:
            scaler = self.scaler_save_pct
        
        if model_type in ['ridge', 'lasso', 'elastic_net']:
            X_train_scaled = scaler.fit_transform(X_train)
            X_test_scaled = scaler.transform(X_test)
            X_train_final = X_train_scaled
            X_test_final = X_test_scaled
        else:
            X_train_final = X_train
            X_test_final = X_test
        
        # Hyperparameter tuning
        cv_folds = min(5, max(3, len(X_train) // 15))
        
        if model_config['search_type'] == 'randomized':
            search = RandomizedSearchCV(
                estimator=model_config['model'],
                param_distributions=model_config['params'],
                n_iter=model_config.get('n_iter', 10),
                cv=cv_folds,
                scoring='r2',
                n_jobs=-1,
                random_state=42
            )
        else:
            search = GridSearchCV(
                estimator=model_config['model'],
                param_grid=model_config['params'],
                cv=cv_folds,
                scoring='r2',
                n_jobs=-1
            )
        
        search.fit(X_train_final, y_train)
        
        # Store model
        if target_name == 'wins':
            self.model_wins = search.best_estimator_
            self.best_params_wins = search.best_params_
        elif target_name == 'shutouts':
            self.model_shutouts = search.best_estimator_
            self.best_params_shutouts = search.best_params_
        elif target_name == 'gaa':
            self.model_gaa = search.best_estimator_
            self.best_params_gaa = search.best_params_
        else:
            self.model_save_pct = search.best_estimator_
            self.best_params_save_pct = search.best_params_
        
        # Predictions and metrics
        y_pred = search.best_estimator_.predict(X_test_final)
        
        mae = mean_absolute_error(y_test, y_pred)
        mse = mean_squared_error(y_test, y_pred)
        rmse = np.sqrt(mse)
        r2 = r2_score(y_test, y_pred)
        
        train_score = search.best_estimator_.score(X_train_final, y_train)
        test_score = r2
        overfitting_ratio = (train_score - test_score) / train_score if train_score > 0 else 0
        
        results = {
            'mae': mae, 'mse': mse, 'rmse': rmse, 'r2': r2,
            'train_r2': train_score, 'test_r2': test_score,
            'overfitting_ratio': overfitting_ratio,
            'cv_mean': search.best_score_,
            'y_test': y_test, 'y_pred': y_pred,
            'model_type': model_type,
            'target_name': target_name,
            'best_params': search.best_params_,
            'n_train': len(X_train), 'n_test': len(X_test),
            'n_features_selected': len(X.columns)
        }
        
        print(f"    {target_name} model - R²: {r2:.3f}, RMSE: {rmse:.4f}")
        return results
    
