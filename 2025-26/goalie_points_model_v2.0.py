class OutputManager:
    """Manages output to both console and file"""
    def __init__(self, output_file=None):
        self.terminal = sys.stdout
        self.log_file = None
        self.output_file_path = output_file
        if output_file:
            try:
                os.makedirs(os.path.dirname(output_file), exist_ok=True)
                self.log_file = open(output_file, 'w', encoding='utf-8')
                print(f"Output will be saved to: {output_file}")
            except Exception as e:
                print(f"Warning: Could not create output file {output_file}: {e}")
    
    def write(self, message):
        self.terminal.write(message)
        self.terminal.flush()
        if self.log_file:
            try:
                self.log_file.write(message)
                self.log_file.flush()
            except Exception as e:
                self.terminal.write(f"\nWarning: Could not write to log file: {e}\n")
    
    def flush(self):
        try:
            self.terminal.flush()
            if self.log_file:
                self.log_file.flush()
        except Exception as e:
            self.terminal.write(f"\nWarning: Could not flush files: {e}\n")
    
    def close(self):
        try:
            if self.log_file:
                self.log_file.flush()
                self.log_file.close()
                self.terminal.write(f"\nOutput saved to: {self.output_file_path}\n")
        except Exception as e:
            self.terminal.write(f"\nWarning: Could not close log file: {e}\n")

