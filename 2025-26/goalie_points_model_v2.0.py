    def _create_team_goal_differential(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Create team goal differential features for goalie context.
        
        Args:
            df: DataFrame with team statistics
            
        Returns:
            DataFrame with team goal differential features added
        """
        print("\nCreating team goal differential features for goalie context...")
        
        # Look for goals for and goals against columns
        goals_for_cols = ['goals_for', 'goalsFor', 'goals_for_team', 'gf', 'GF']
        goals_against_cols = ['goals_against', 'goalsAgainst', 'goals_against_team', 'ga', 'GA']
        
        goals_for_col = goals_against_col = None
        
        for col in goals_for_cols:
            if col in df.columns:
                goals_for_col = col
                break
        
        for col in goals_against_cols:
            if col in df.columns:
                goals_against_col = col
                break
        
        if goals_for_col and goals_against_col:
            # Create team goal differential
            df['team_goal_differential'] = df[goals_for_col].fillna(0) - df[goals_against_col].fillna(0)
            
            # Create team strength metrics (important for goalie performance)
            df['team_goals_for_per_game'] = df[goals_for_col].fillna(0) / df.get('games_played_team', df.get('games_played', 82)).replace(0, 82)
            df['team_goals_against_per_game'] = df[goals_against_col].fillna(0) / df.get('games_played_team', df.get('games_played', 82)).replace(0, 82)
            df['team_goal_diff_per_game'] = df['team_goal_differential'] / df.get('games_played_team', df.get('games_played', 82)).replace(0, 82)
            
            # Team strength indicators (crucial for goalie wins and shutouts)
            df['strong_offensive_team'] = (df['team_goals_for_per_game'] > df['team_goals_for_per_game'].quantile(0.75)).astype(int)
            df['strong_defensive_team'] = (df['team_goals_against_per_game'] < df['team_goals_against_per_game'].quantile(0.25)).astype(int)
            df['elite_team'] = ((df['team_goal_diff_per_game'] > df['team_goal_diff_per_game'].quantile(0.8)) & 
                               (df['team_goals_for_per_game'] > df['team_goals_for_per_game'].median())).astype(int)
            
            print(f"  Team goal differential statistics:")
            print(f"    Mean: {df['team_goal_differential'].mean():.1f}")
            print(f"    Range: {df['team_goal_differential'].min():.0f} to {df['team_goal_differential'].max():.0f}")
            print(f"    Strong offensive teams: {df['strong_offensive_team'].sum()} observations")
            print(f"    Strong defensive teams: {df['strong_defensive_team'].sum()} observations")
            print(f"    Elite teams: {df['elite_team'].sum()} observations")
            
        else:
            print(f"  Warning: Could not find goals for/against columns")
            print(f"  Available columns: {[col for col in df.columns if 'goal' in col.lower()]}")
            # Create placeholder features
            df['team_goal_differential'] = 0
            df['team_goals_for_per_game'] = 3.0
            df['team_goals_against_per_game'] = 3.0  
            df['team_goal_diff_per_game'] = 0
            df['strong_offensive_team'] = 0
            df['strong_defensive_team'] = 0
            df['elite_team'] = 0
        
        return df
    
    def _create_quadruple_targets(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Create quadruple target variables using correct goalie column names:
        games_played_player, wins_player, shutouts, goals_against_avg, save_pct
        
        Args:
            df: DataFrame with goalie statistics
            
        Returns:
            DataFrame with quadruple target variables for goalies
        """
        print("\nCreating quadruple target variables for goalies (using correct column names)...")
        
        # Handle games played column - use games_played_player consistently
        if 'games_played_player' in df.columns:
            df['games_played_player'] = df['games_played_player'].fillna(0).clip(lower=0)
            print("Using 'games_played_player' column for games played")
            # Don't create a separate games_played column - use games_played_player throughout
        else:
            raise ValueError(f"Cannot find 'games_played_player' column. Available columns: {list(df.columns)}")
        
        # Add games started as additional feature if available
        if 'games_started' in df.columns:
            df['games_started'] = df['games_started'].fillna(0).clip(lower=0)
            print("Found 'games_started' column - adding as feature")
        
        # 1. WINS TARGET - use goalie-specific wins column
        if 'wins_player' in df.columns:
            df['total_wins'] = df['wins_player'].fillna(0).clip(lower=0)
            print("Using 'wins_player' column for wins calculation")
        else:
            # Fallback to other wins variations
            wins_cols = ['wins', 'w', 'W', 'wins_goalie', 'goalie_wins']
            wins_col = None
            
            for col in wins_cols:
                if col in df.columns:
                    wins_col = col
                    break
            
            if wins_col:
                df['total_wins'] = df[wins_col].fillna(0).clip(lower=0)
                print(f"Using '{wins_col}' column for wins calculation")
            else:
                print("Warning: No wins column found - creating placeholder")
                df['total_wins'] = 0
        
        # 2. SHUTOUTS TARGET - use shutouts column (handle sparse data)
        if 'shutouts' in df.columns:
            df['total_shutouts'] = pd.to_numeric(df['shutouts'], errors='coerce').fillna(0).clip(lower=0)
            print("Using 'shutouts' column for shutouts calculation")
            
            # Debug shutouts data
            shutouts_nonzero = (df['total_shutouts'] > 0).sum()
            shutouts_total = len(df)
            shutouts_max = df['total_shutouts'].max() if len(df) > 0 else 0
            print(f"  Shutouts data check: {shutouts_nonzero}/{shutouts_total} goalies have shutouts (max: {shutouts_max})")
            
            if shutouts_nonzero == 0:
                print("  WARNING: No goalies have shutouts in dataset - this will cause prediction issues")
            elif shutouts_nonzero < 5:
                print(f"  WARNING: Very few shutouts ({shutouts_nonzero}) - model may struggle with prediction")
        else:
            # Fallback to other shutouts variations
            shutouts_cols = ['so', 'SO', 'shutout', 'shutouts_goalie']
            shutouts_col = None
            
            for col in shutouts_cols:
                if col in df.columns:
                    shutouts_col = col
                    break
            
            if shutouts_col:
                df['total_shutouts'] = pd.to_numeric(df[shutouts_col], errors='coerce').fillna(0).clip(lower=0)
                print(f"Using '{shutouts_col}' column for shutouts calculation")
            else:
                print("Warning: No shutouts column found - creating placeholder")
                df['total_shutouts'] = 0
        
        # 3. GAA TARGET - use goalie-specific GAA column
        if 'goals_against_avg' in df.columns:
            df['goals_against_average'] = pd.to_numeric(df['goals_against_avg'], errors='coerce').fillna(3.0).clip(lower=0, upper=10)
            print("Using 'goals_against_avg' column for GAA")
        else:
            # Fallback to other GAA variations
            gaa_cols = ['gaa', 'GAA', 'goals_against_average', 'goalsAgainstAverage']
            gaa_col = None
            
            for col in gaa_cols:
                if col in df.columns:
                    gaa_col = col
                    break
            
            if gaa_col:
                df['goals_against_average'] = pd.to_numeric(df[gaa_col], errors='coerce').fillna(3.0).clip(lower=0, upper=10)
                print(f"Using '{gaa_col}' column for GAA")
            else:
                print("Warning: No GAA column found - creating placeholder")
                df['goals_against_average'] = 3.0
        
        # 4. SAVE PERCENTAGE TARGET - use save_pct column
        if 'save_pct' in df.columns:
            # Handle percentage format (might be 0-1 or 0-100)
            save_values = pd.to_numeric(df['save_pct'], errors='coerce')
            if save_values.max() > 1:
                df['save_percentage'] = (save_values / 100).fillna(0.900).clip(lower=0.5, upper=1.0)
            else:
                df['save_percentage'] = save_values.fillna(0.900).clip(lower=0.5, upper=1.0)
            print("Using 'save_pct' column for save percentage")
        else:
            # Fallback to other save percentage variations
            save_pct_cols = ['sv_pct', 'save_percentage', 'savePercentage', 'SV%']
            save_pct_col = None
            
            for col in save_pct_cols:
                if col in df.columns:
                    save_pct_col = col
                    break
            
            if save_pct_col:
                save_values = pd.to_numeric(df[save_pct_col], errors='coerce')
                if save_values.max() > 1:
                    df['save_percentage'] = (save_values / 100).fillna(0.900).clip(lower=0.5, upper=1.0)
                else:
                    df['save_percentage'] = save_values.fillna(0.900).clip(lower=0.5, upper=1.0)
                print(f"Using '{save_pct_col}' column for save percentage")
            else:
                print("Warning: No save percentage column found - creating placeholder")
                df['save_percentage'] = 0.900
        
        # Create per-game targets for wins and shutouts using games_played_player consistently
        valid_games_mask = df['games_played_player'] > 0
        
        # Wins per game
        df.loc[valid_games_mask, 'wins_per_game'] = (
            df.loc[valid_games_mask, 'total_wins'] / df.loc[valid_games_mask, 'games_played_player']
        )
        df.loc[~valid_games_mask, 'wins_per_game'] = 0
        
        # Shutouts per game
        df.loc[valid_games_mask, 'shutouts_per_game'] = (
            df.loc[valid_games_mask, 'total_shutouts'] / df.loc[valid_games_mask, 'games_played_player']
        )
        df.loc[~valid_games_mask, 'shutouts_per_game'] = 0
        
        # Debug per-game calculations
        print(f"Shutouts per game statistics after calculation:")
        shutouts_pg_nonzero = (df['shutouts_per_game'] > 0).sum()
        shutouts_pg_max = df['shutouts_per_game'].max() if len(df) > 0 else 0
        print(f"  Non-zero shutouts per game: {shutouts_pg_nonzero}/{len(df)} ({shutouts_pg_max:.4f} max)")
        
        # GAA and save percentage remain as is (not per-game metrics)
        
        # Statistics for all targets
        wins_stats = df[df['wins_per_game'] > 0]['wins_per_game'].describe()
        
        # Handle shutouts stats carefully since they might be sparse
