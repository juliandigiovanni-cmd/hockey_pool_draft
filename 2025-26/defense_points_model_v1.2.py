    def _get_single_model_importance(self, model, feature_names, model_name, top_n):
        """Get feature importance for a single model."""
        # Get importance values
        if hasattr(model, 'feature_importances_'):
            importance = model.feature_importances_
        else:
            importance = np.abs(model.coef_)
        
        importance_df = pd.DataFrame({
            'feature': feature_names,
            'importance': importance,
            'model': model_name
        }).sort_values('importance', ascending=False)
        
        # ENHANCED categorization for defensemen features
        def categorize_defensive_feature(feature_name):
            if 'covid' in feature_name.lower():
                return "COVID"
            elif 'years_played' in feature_name or 'rookie' in feature_name or 'prime' in feature_name or 'veteran' in feature_name:
                return "EXPERIENCE"
            elif '_x_' in feature_name or 'interaction' in feature_name:
                return "INTERACTION"
            elif 'plus_minus' in feature_name or 'pm_' in feature_name:
                return "PLUS_MINUS"
            elif 'rel_team' in feature_name or 'context' in feature_name:
                return "ENHANCED_TEAM"  # v1.2 enhancement
            elif any(team_indicator in feature_name.lower() for team_indicator in ['wins', 'losses', 'goals_for', 'goals_against']):
                return "TEAM"
            elif feature_name.startswith('pp'):
                return "POWERPLAY"
            elif any(metric in feature_name for metric in ['goals', 'assists', 'points', 'shots']):
                return "OFFENSIVE"
            elif 'time_on_ice' in feature_name or 'toi' in feature_name:
                return "ICE_TIME"
            elif 'ratio' in feature_name or 'defensive' in feature_name:
                return "ENHANCED_DEFENSIVE"  # v1.2 enhancement
            else:
                return "OTHER"
        
        importance_df['category'] = importance_df['feature'].apply(categorize_defensive_feature)
        
        return importance_df.head(top_n)
    
