    def _create_enhanced_team_context_features(self, df_eng: pd.DataFrame, lag_columns: List[str]) -> None:
        """ENHANCED team context features for plus/minus modeling (v1.2)."""
        print("  Creating ENHANCED team context features for plus/minus...")
        
        # Team performance metrics that affect plus/minus
        team_lags = [col for col in lag_columns 
                    if any(team in col for team in ['wins_lag', 'goals_for_lag', 'goals_against_lag', 'goal_diff_lag'])]
        
        team_context_count = 0
        
        # ENHANCED: Plus/minus relative to team strength
        if 'plus_minus_per_game_lag1' in df_eng.columns:
            for team_col in team_lags[:6]:  # Top team metrics
                if team_col in df_eng.columns:
                    # Normalize plus/minus by team performance
                    interaction_name = f'pm_rel_team_{team_col}'
                    team_values = df_eng[team_col]
                    if team_values.std() > 0:  # Avoid division by zero
                        normalized_team = (team_values - team_values.mean()) / team_values.std()
                        df_eng[interaction_name] = df_eng['plus_minus_per_game_lag1'] * normalized_team
                        team_context_count += 1
        
        # ENHANCED: Ice time relative to team context
        if 'time_on_ice_per_game_lag1' in df_eng.columns:
            for team_col in team_lags[:3]:  # Key team metrics
                if team_col in df_eng.columns:
                    interaction_name = f'toi_team_context_{team_col}'
                    df_eng[interaction_name] = df_eng['time_on_ice_per_game_lag1'] * df_eng[team_col]
                    team_context_count += 1
        
        print(f"    Created {team_context_count} ENHANCED team context features")
    
